    def regenerate_base_blobs(self):
        self.palette = generate_random_palette(int(self.palette_size), blend_with_white=self.blend_with_white)

        while True:
            bg_cand = generate_random_palette(1, blend_with_white=0.1)[0]
            min_dist = min(np.linalg.norm(np.array(bg_cand) - np.array(c)) for c in self.palette)
            if min_dist > 0.35:
                self.bg_color = bg_cand
                break

        bg_luminance = 0.299 * self.bg_color[0] + 0.587 * self.bg_color[1] + 0.114 * self.bg_color[2]
        self.title_color = '#FFFFFF' if bg_luminance < 0.5 else '#0A0A0A'

        self.base_blobs = []
        for i in range(int(self.n_layers)):
            radius = random.uniform(self.max_radius * 0.4, self.max_radius)
            wobble_factor = random.uniform(0.05, self.max_wobble)
            center_x = random.uniform(0.1, 0.9)
            center_y = random.uniform(0.1, 0.9)
            color = random.choice(self.palette)
            alpha = random.uniform(self.base_alpha * 0.8, min(1.0, self.base_alpha * 1.2))

            self.base_blobs.append({
                'radius': radius,
                'wobble': wobble_factor,
                'cx': center_x,
                'cy': center_y,
                'color': color,
                'alpha': alpha
            })

    def draw_poster(self):
        with self.out:
            clear_output(wait=True)
            fig, ax = plt.subplots(figsize=(8, 8))
            ax.set_aspect('equal', adjustable='box')
            ax.set_xlim(-0.1, 1.1)
            ax.set_ylim(-0.1, 1.1)
            ax.axis('off')

            fig.patch.set_facecolor(self.bg_color)
            ax.set_facecolor(self.bg_color)

            def draw_3d_blob(blob, layer_index):
                x_coords, y_coords = generate_blob_coords(
                    blob['radius'], blob['wobble'], blob['cx'], blob['cy'], shape_type=self.selected_shape
                )

                z_base = (layer_index + 1) * 3

                shadow_offset_x = 0.015
                shadow_offset_y = -0.015
                ax.fill(
                    x_coords + shadow_offset_x,
                    y_coords + shadow_offset_y,
                    facecolor='#111111',
                    edgecolor='none',
                    alpha=0.18 * blob['alpha'],
                    zorder=z_base
                )

                ax.fill(
                    x_coords,
                    y_coords,
                    facecolor='#222222',
                    edgecolor='none',
                    alpha=blob['alpha'],
                    zorder=z_base + 1
                )

                body_offset_x = -0.005
                body_offset_y = 0.005
                ax.fill(
                    x_coords + body_offset_x,
                    y_coords + body_offset_y,
                    facecolor=blob['color'],
                    edgecolor=blob['color'],
                    linewidth=1.0,
                    alpha=blob['alpha'],
                    zorder=z_base + 2
                )

            for i, blob in enumerate(self.base_blobs):
                draw_3d_blob(blob, i)

            for i, blob in enumerate(self.custom_blobs):
                draw_3d_blob(blob, len(self.base_blobs) + i)

            # Draw the title on top of all blobs (zorder=1000)
            if self.title_text:
                ax.text(0.05, 0.95, self.title_text, transform=ax.transAxes,
                         fontsize=self.title_fontsize, family=self.title_fontfamily,
                         color=self.title_color, ha='left', va='top', zorder=1000)

            plt.show()

    def on_value_change(self, change):
        self.n_layers = self.slider_layers.value
        self.max_wobble = self.slider_wobble.value
        self.max_radius = self.slider_radius.value
