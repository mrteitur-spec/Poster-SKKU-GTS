import matplotlib.pyplot as plt
import numpy as np
import random

"""### (a) Color Palette Function

This function generates a list of random, vibrant colors. We'll generate random RGB tuples to ensure a diverse palette without relying on predefined sets.
"""

def generate_random_palette(num_colors, blend_with_white=0.3):
    """
    Generates a list of highly diverse, vibrant, and rich RGB color tuples,
    with an adjustable blend with white to preserve vibrant color diversity.
    """
    palette = []
    for _ in range(num_colors):
        # Generate highly diverse base colors across the full spectrum
        r = random.uniform(0.0, 1.0)
        g = random.uniform(0.0, 1.0)
        b = random.uniform(0.0, 1.0)

        # Ensure we don't get purely dark/grayish muddy colors
        max_val = max(r, g, b)
        if max_val < 0.5:
            r, g, b = r / max_val * 0.7, g / max_val * 0.7, b / max_val * 0.7

        # Blend with white (lower default blend factor yields more diverse and saturated colors)
        r_vibrant = r * (1 - blend_with_white) + 1.0 * blend_with_white
        g_vibrant = g * (1 - blend_with_white) + 1.0 * blend_with_white
        b_vibrant = b * (1 - blend_with_white) + 1.0 * blend_with_white

        palette.append((r_vibrant, g_vibrant, b_vibrant))
    return palette

"""### (b) Blob Generator Function

This function creates the coordinates for a single organic 'blob' shape. It starts with a circle and then adds random perturbations (wobble) to its radius at different angles to create an organic, irregular form. The center of the blob is also parameterized to allow for flexible positioning.
"""

def generate_blob_coords(radius, wobble_factor, center_x, center_y, shape_type="Circle", num_points=120):
    """
    Generates (x, y) coordinates for an organic blob starting from a base shape
    and perturbing it dynamically.
    """
    theta = np.linspace(0, 2 * np.pi, num_points, endpoint=False)

    # Define the base radial structure based on the selected shape
    if shape_type == "Heart":
        x_base = 16 * np.sin(theta)**3
        y_base = 13 * np.cos(theta) - 5 * np.cos(2*theta) - 2 * np.cos(3*theta) - np.cos(4*theta)
        norm = np.sqrt(x_base**2 + y_base**2)
        max_norm = np.max(norm) if np.max(norm) > 0 else 1.0
        x_base = (x_base / max_norm) * radius
        y_base = (y_base / max_norm) * radius + (0.1 * radius)
    elif shape_type == "Rectangle":
        r_base = radius / np.maximum(np.abs(np.cos(theta)), np.abs(np.sin(theta)))
        x_base = r_base * np.cos(theta)
        y_base = r_base * np.sin(theta)
    elif shape_type == "Star":
        star_pattern = 1.0 + 0.5 * np.sin(5 * theta)
        x_base = radius * star_pattern * np.cos(theta)
        y_base = radius * star_pattern * np.sin(theta)
    elif shape_type == "Triangle":
        r_base = radius / (np.cos(theta - (2 * np.pi / 3) * np.floor((3 * theta + np.pi) / (2 * np.pi))))
        r_base = np.clip(r_base, 0, radius * 2.0)
        x_base = r_base * np.cos(theta)
        y_base = r_base * np.sin(theta)
    elif shape_type == "Shield":
        r_base = radius * (1.0 - 0.3 * np.abs(np.sin(theta)) * (theta > np.pi))
        x_base = r_base * np.cos(theta)
        y_base = r_base * np.sin(theta)
    elif shape_type == "Gun":
        # Parametric approximate pistol shape silhouette
        raw_x = np.cos(theta)
        raw_y = np.sin(theta)
        # Extend left/up for the barrel and down for the grip
        for i, t in enumerate(theta):
            if 0 <= t < np.pi/2:
                raw_x[i] *= 1.8  # barrel length
                raw_y[i] *= 0.6  # barrel height
            elif np.pi/2 <= t < np.pi:
                raw_x[i] *= 0.8
                raw_y[i] *= 0.8
            elif np.pi <= t < 1.5 * np.pi:
                raw_x[i] *= 0.7  # grip width
                raw_y[i] *= 1.6  # grip length
        norm = np.sqrt(raw_x**2 + raw_y**2)
        max_norm = np.max(norm) if np.max(norm) > 0 else 1.0
        x_base = (raw_x / max_norm) * radius
        y_base = (raw_y / max_norm) * radius
    elif shape_type == "Trump":
        # Fun approximation profile: face + prominent forward hair tuft
        raw_x = np.cos(theta)
        raw_y = np.sin(theta)
        for i, t in enumerate(theta):
            if 0 <= t < np.pi/3:
                raw_x[i] *= 1.7  # Front hair sweep / coiffure
                raw_y[i] *= 1.4
            elif np.pi/3 <= t < np.pi/2:
                raw_x[i] *= 1.3
            elif 1.5*np.pi <= t < 2*np.pi:
                raw_x[i] *= 1.2  # Forehead and nose projection profile
        norm = np.sqrt(raw_x**2 + raw_y**2)
        max_norm = np.max(norm) if np.max(norm) > 0 else 1.0
        x_base = (raw_x / max_norm) * radius
        y_base = (raw_y / max_norm) * radius
    else: # Default: Circle
        x_base = radius * np.cos(theta)
        y_base = radius * np.sin(theta)

    # Add random perturbations (wobble) to the base coordinates
    perturb_x = np.random.uniform(-wobble_factor * radius, wobble_factor * radius, num_points)
    perturb_y = np.random.uniform(-wobble_factor * radius, wobble_factor * radius, num_points)

    x_coords = x_base + perturb_x + center_x
    y_coords = y_base + perturb_y + center_y

    return x_coords, y_coords

"""### (c) Main Drawing Function `generate_poster()` with Parameters

This function orchestrates the creation of the entire poster. It combines the color palette and blob generator to draw multiple layered shapes on a Matplotlib figure. Parameters allow detailed control over the number of layers, their size, wobble, transparency, and the overall color scheme. A `seed` is included for reproducibility.
"""

def generate_poster(
    seed=None,
    n_layers=8,
    radius_range=(0.1, 0.4),
    wobble_range=(0.1, 0.3),
    palette_size=5,
    blend_with_white=0.15,
    figure_size=(10, 10),
    base_alpha=0.7,
    title_text="",
    title_fontsize=62
):
    """
    Creates and displays a generative artistic poster with a background color
    guaranteed to be highly distinct from the organic patterns and title.
    """
    if seed is not None:
        random.seed(seed)
        np.random.seed(seed)

    n_layers = max(6, min(10, n_layers))

    fig, ax = plt.subplots(figsize=figure_size)
    ax.set_aspect('equal', adjustable='box')

    ax.set_xlim(-0.1, 1.1)
    ax.set_ylim(-0.1, 1.1)
    ax.axis('off')

    # Generate a distinct base palette for the patterns (blobs)
    palette = generate_random_palette(palette_size, blend_with_white=blend_with_white)

    # Generate a background color that is completely distinct from any blob color
    # We loop until we find a color with a high Euclidean distance from all palette colors
    while True:
        bg_color = generate_random_palette(1, blend_with_white=0.1)[0]
        # Measure min distance to any color in the blob palette
        min_dist = min(np.linalg.norm(np.array(bg_color) - np.array(c)) for c in palette)
        if min_dist > 0.35: # Ensure strong color distinction
            break

    # Set figure background color dynamically
    fig.patch.set_facecolor(bg_color)
    ax.set_facecolor(bg_color)

    # Determine high-contrast title color based on background brightness (luminance)
    bg_luminance = 0.299 * bg_color[0] + 0.587 * bg_color[1] + 0.114 * bg_color[2]
    title_color = '#FFFFFF' if bg_luminance < 0.5 else '#0A0A0A'

    for i in range(n_layers):
        radius = random.uniform(radius_range[0], radius_range[1])
        wobble_factor = random.uniform(wobble_range[0], wobble_range[1])
        center_x = random.uniform(0, 1)
        center_y = random.uniform(0, 1)
        color = random.choice(palette)
        current_alpha = random.uniform(base_alpha * 0.8, min(1.0, base_alpha * 1.2))

        x_coords, y_coords = generate_blob_coords(radius, wobble_factor, center_x, center_y)

        # Use a high contrast border overlay for maximum pop
        ax.fill(x_coords, y_coords, facecolor=color, edgecolor='#111111', linewidth=1.5, alpha=current_alpha, zorder=i)

    if title_text:
        ax.text(0.05, 1.05, title_text, transform=ax.transAxes, fontsize=title_fontsize,
                color=title_color, ha='left', va='top', zorder=n_layers + 1)

    plt.tight_layout()
    return fig, ax

